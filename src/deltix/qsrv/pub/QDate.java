package deltix.qsrv.pub;

/**
 *  A simple record containing a year, a month and a day of month.
 */
public class QDate {
    /**
     *  The year
     */
    public int          year;
    
    /**
     *  The month, 1 - 12
     */
    public int          month;
    
    /**
     *  The day of month, 1 - 31
     */
    public int          day;    
}
